def _now_iso():
    return datetime.now(timezone.utc).isoformat()


def _http_get(url, timeout=10):
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            return r.status, r.read()
    except urllib.error.HTTPError as e:
        return e.code, b""
    except Exception:
        return -1, b""


def _parse_robots(text):
    """Parse robots.txt → dict: disallow, allow, sitemap, crawl_delay."""
    result = {"disallow": [], "allow": [], "sitemap": [], "crawl_delay": None}
    if not text:
        return result
    current_agent = None
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if ":" not in line:
            continue
        k, v = line.split(":", 1)
        k, v = k.strip().lower(), v.strip()
        if k == "user-agent":
            current_agent = v
        elif k == "disallow" and v:
            result["disallow"].append((current_agent, v))
        elif k == "allow" and v:
            result["allow"].append((current_agent, v))
        elif k == "sitemap":
            result["sitemap"].append(v)
        elif k == "crawl-delay" and v:
            result["crawl_delay"] = v
    return result


